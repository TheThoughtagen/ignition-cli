    // (configure-created tags carry NO AlertAckMode). Same-parent
    // LEAF paths: a multi-path export answers the `{"tags":[...]}`
    // wrapper (single-path would answer the folder subtree itself).
    let orig_path = tmp.path().join("orig.json");
