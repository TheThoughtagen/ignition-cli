///    carries the additive `history:` block naming the live provider,
/// 4. write 42/43/44, then poll `tags history query` (bounded — the
///    tag-group scan stores at 40–50 s cadence, 13-01 data probe)
///    until the WRITTEN 44 appears: DATA rows are the closure
///    evidence. A null-data outcome on this branch is a DRIFT
///    FINDING (the gate fails loudly; 13-LIVE-GATE.md records it —
///    capture wins, never code around it),
/// 5. FINALLY: tag + historian deletion runs regardless of the
///    body's outcome, and the historian delete VERIFIES gone
///    (re-find → 404 — the corrected harness chain).
#[tokio::test]
#[ignore = "opt-in e2e: set IGNITION_LIVE_URL + IGNITION_LIVE_TOKEN + IGNITION_LIVE_MUTATIONS=1"]
async fn live_tags_history_bindings() {
    let Some(env) = live_env_mutations() else {
        skip(
            "IGNITION_LIVE_MUTATIONS=1 (with URL+TOKEN) not set — refusing to touch a live gateway",
        );
        return;
    };
    let (_dir, config) = isolated_live_config(&env);
    // THE serializer: one live gate at a time (shared gateway state).
    let _gate = LIVE_GATE.lock().await;
    // UNIQUE historian AND tag name per run (the 11-06 discipline —
    // dozens of same-name cycles degrade a rig's tag model; virgin
    // namespaces. The 13-04 rig-A runs proved the class applies to
    // TAG paths too: a delete/recreated [default]P13H/T1 never
    // re-registered with the historian while a fresh path flowed on
    // the first scan).
    let suffix = now_ms();
    let historian = format!("p13hist{suffix}");
    let tag = format!("[default]P13H/T{suffix}");

    // Pre-clean leftovers (idempotent re-runs): the tag first (create
    // over an existing node would abort), then the historian.
    clean_tag_configs(&config, &env, &[&tag]);
    delete_internal_historian(&env, &historian).await;

    // Routes first: history query refuses exit 6 without them. The
    // import can race a partial route mount on a fresh gateway (the
    // 13-04 rig-A run: three routes landed, `tags` answered 405 — the
    // documented 11-06 mount-race class; the redeploy-overwrite heals
    // it), so the step VERIFIES the sweep afterwards and redeploys
    // ONCE on a miss.
    let out = ign(&config, &env, &["webdev", "deploy", "--compact"]);
    expect_ok("deploy (the tagHistory route's precondition)", &out);
    // The sweep itself is POLLED (30 s): a just-imported servlet's
    // first activation can lag seconds-to-minutes (the 11-06
    // first-activation tolerance) — a single-shot sweep would fail
    // the heal path spuriously (13-04 rig-B run 1).
    let sweep_all_present = |config: &Path, env: &LiveEnv| -> bool {
        let deadline = std::time::Instant::now() + std::time::Duration::from_secs(30);
        loop {
            let out = ign(config, env, &["webdev", "status", "--compact"]);
            let healthy = out.status.success()
                && ["tags", "tagConfig", "alarms", "tagHistory"]
                    .iter()
                    .all(|route| {
                        data_envelope(&out)["data"]["routes"]
                            .as_array()
                            .is_some_and(|rows| {
                                rows.iter().any(|row| {
                                    row["route"].as_str() == Some(*route)
                                        && row["status"].as_str() == Some("present")
                                })
                            })
                    });
            if healthy || std::time::Instant::now() >= deadline {
                return healthy;
            }
            std::thread::sleep(std::time::Duration::from_secs(3));
        }
    };
    if !sweep_all_present(&config, &env) {
        eprintln!("deploy: mount race (a core route absent) — redeploying once (11-06 lesson)");
        let out = ign(&config, &env, &["webdev", "deploy", "--compact"]);
        expect_ok("redeploy (mount-race heal)", &out);
        assert!(
            sweep_all_present(&config, &env),
            "core routes still absent after the heal redeploy"
        );
    }

    let outcome = historian_binding_body(&config, &env, &historian, &tag).await;

    // FINALLY: self-cleaning regardless of the body's outcome (the
    // corrected historian chain verifies gone).
    clean_tag_configs(&config, &env, &[&tag]);
    delete_internal_historian(&env, &historian).await;

    if let Err(message) = outcome {
        panic!("{message}");
    }
}

/// The gate's asserting body, Result-shaped so the FINALLY above
/// always runs (ensure_ok instead of expect_ok inside).
///
/// The bind→write→prove sequence runs inside a 3-cycle SELF-HEALING
/// loop (the 11-06 live-truth recovery, proven again on 13-04 rig A):
/// a tag created in the deploy import's model-rebuild tail can read
/// back its config, answer writes Good, and yet NEVER register with
/// the historian (rows stay empty from birth — rig A runs 2–4, while
/// identical probes created OUTSIDE that window flowed on the first
/// write). The proven recovery is delete → settle → recreate.
async fn historian_binding_body(
    config: &Path,
    env: &LiveEnv,
    historian: &str,
    tag: &str,
) -> Result<(), String> {
    // (1) The historian — native REST, no database.
    provision_internal_historian(env, historian).await;

    let mut last_miss = String::new();
    for cycle in 1..=3 {
        if cycle > 1 {
            eprintln!(
                "bind cycle {cycle}: prior cycle stored nothing — delete → settle → recreate"
            );
        }
        // Settle FIRST (the deploy import's model-rebuild tail on
        // cycle 1; the recreate tail on later cycles — 30 s, rig B's
        // just-RUNNING gateway orphaned every 15 s settle), then
        // clear any prior cycle's node.
        tokio::time::sleep(std::time::Duration::from_secs(30)).await;
        clean_tag_configs(config, env, std::slice::from_ref(&tag));

        // (2) The bound tag — the closure recipe, complete node shape
        // + the captured three-key field set.
        let out = ign_stdin(
            config,
            env,
            &["tags", "config", "create", tag, "--file", "-", "--compact"],
            &format!(
                r#"{{"tagType": "AtomicTag", "dataType": "Int4", "value": 0, "historyEnabled": true, "historyProvider": "{historian}", "sampleMode": "TagGroup"}}"#
            ),
        );
        ensure_ok("config create the bound tag (closure recipe)", &out)?;

        // (3) TAGS-13 live assert — the HUMAN render carries the
        // additive history block with the LIVE provider name (no
        // --compact).
        let out = ign(config, env, &["tags", "config", "get", tag]);
        ensure_ok("config get the bound tag", &out)?;
        let stdout = String::from_utf8_lossy(&out.stdout);
        for needle in [
            "history:",
            "  enabled: true",
            &format!("  provider: {historian}"),
            "  sample mode: TagGroup",
        ] {
            if !stdout.contains(needle) {
                return Err(format!("TAGS-13 live render missing {needle:?}:\n{stdout}"));
            }
        }
        println!("TAGS-13 live: history block present for {tag} (provider {historian})");

        // (4) Write values (spaced), then poll the query until the
        // WRITTEN 44 lands — the stored row can ride the write
        // directly (~seconds, live-proven) or the tag-group scan
        // (40–50 s cadence, the 13-01 data probe), so the per-cycle
        // poll is bounded and patient.
        let start_ms = now_ms() - 60_000;
        for value in [42, 43, 44] {
            let out = ign(
                config,
                env,
                &[
                    "tags",
                    "write",
                    tag,
                    "--value",
                    &value.to_string(),
                    "--compact",
                ],
            );
            ensure_ok("write a history value", &out)?;
            tokio::time::sleep(std::time::Duration::from_millis(1_100)).await;
        }
        let end_ms = now_ms() + 5_000;
        let query_args = |start_ms: i64, end_ms: i64| {
            vec![
                "tags".to_string(),
                "history".to_string(),
                "query".to_string(),
                tag.to_string(),
                "--start".to_string(),
                start_ms.to_string(),
                "--end".to_string(),
                end_ms.to_string(),
                "--compact".to_string(),
            ]
        };
        let deadline = std::time::Instant::now() + std::time::Duration::from_secs(75);
        loop {
            let args = query_args(start_ms, end_ms);
            let refs: Vec<&str> = args.iter().map(String::as_str).collect();
            let out = ign(config, env, &refs);
            ensure_ok("history query", &out)?;
            let envelope = data_envelope(&out);
            // Structural pins while we're here (the 05-06 wire
            // truths): t_stamp leads, the tag column rides
            // provider-relative.
            let columns = envelope["data"]["columns"]
                .as_array()
                .cloned()
                .unwrap_or_default();
            if columns.first().and_then(Value::as_str) != Some("t_stamp") {
                return Err(format!("history query lost the t_stamp column: {envelope}"));
            }
            let relative = tag
                .trim_start_matches('[')
                .split_once(']')
                .map(|(_, rest)| rest)
                .unwrap_or(tag);
            if !columns
                .iter()
                .any(|column| column.as_str() == Some(relative))
            {
                return Err(format!(
                    "the tag column rides provider-relative: {envelope}"
                ));
            }
            if history_rows_contain(&envelope, 44) {
                println!("SC-4 closure evidence: written value 44 proven in history ({historian})");
                return Ok(());
            }
            last_miss = serde_json::to_string(&envelope["data"]["rows"]).unwrap_or_default();
            if std::time::Instant::now() >= deadline {
                break;
            }
            eprintln!("history: no 44 yet (scan cadence 40–50 s) — rows so far: {last_miss}");
            tokio::time::sleep(std::time::Duration::from_secs(15)).await;
        }
    }
    Err(format!(
        "CLOSURE DRIFT FINDING: the 13-01 recipe live-proved data flow, but 3 self-healing \
         cycles of polling never surfaced the written 44 (last rows: {last_miss}) — record \
         in 13-LIVE-GATE.md (capture wins; never code around it)"
    ))
}

/// THE alarm lifecycle live fixture (05-06, TAGS-07) — configure a
/// tag with a LIST-form alarm (AboveValue 100, High — the
/// research-proven configure shape) → write past the setpoint →
/// poll `alarms active` until the event appears (bounded) → ack with
/// note+username (the 3-arg form) → assert the state flip to
/// `Active, Acknowledged` + the remainder shape → the history leg
/// (a default rig asserts the honest `alarm_journal_missing`
/// refusal LIVE — the pinned default-rig path; a journal-provisioned
/// rig asserts rows) → the journal stretch is SKIP-WITH-REASON (the
/// sidecar-postgres chain is documented in the README; the wiremock
/// pins carry the capability proof).
#[tokio::test]
#[ignore = "opt-in e2e: set IGNITION_LIVE_URL + IGNITION_LIVE_TOKEN + IGNITION_LIVE_MUTATIONS=1"]
async fn live_tags_alarm_lifecycle() {
    let Some(env) = live_env_mutations() else {
        skip(
            "IGNITION_LIVE_MUTATIONS=1 (with URL+TOKEN) not set — refusing to touch a live gateway",
        );
        return;
    };
    let (_dir, config) = isolated_live_config(&env);
    // THE serializer: one live gate at a time (shared gateway state).
    let _gate = LIVE_GATE.lock().await;
    // UNIQUE provider name per run (11-06 live-truth): dozens of
    // same-name delete/recreate cycles on one rig eventually degrade
    // that name's tag model (Error_Configuration persisting minutes —
    // seen on both rigs after repeated suite runs). Disposable rigs
    // get disposable names: each run lands in a virgin namespace.
    let provider = format!(
        "p5alarm{}",
        std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .expect("clock")
            .as_secs()
    );
    let tag = format!("[{provider}]AlarmTag");

    // Routes first: every alarms verb refuses exit 6 without them.
    let out = ign(&config, &env, &["webdev", "deploy", "--compact"]);
    expect_ok("deploy (the alarms route's precondition)", &out);

    // SELF-HEALING SETUP (11-06 live-truth, both rigs): a recreate
    // can race the old provider model's teardown tail — the fresh
    // provider's tags answer Error_Configuration, sometimes for a
    // minute-plus. The observed recovery is simply another
    // delete→settle→recreate cycle (proven live), so the setup loops:
    // clean → settle → create → config-create → readiness poll; a
    // cycle that never reaches Good tears down and retries (3 cycles
    // × 20s readiness window).
    for _ in 0..3 {
        clean_provider(&config, &env, &provider);
        let deadline = std::time::Instant::now() + std::time::Duration::from_secs(30);
        loop {
            let out = ign(&config, &env, &["tags", "provider", "list", "--compact"]);
            expect_ok("provider list (settle poll)", &out);
            let envelope = data_envelope(&out);
            let gone = !envelope["data"]["providers"]
                .as_array()
                .expect("providers[]")
                .iter()
                .any(|p| p["name"] == provider);
            if gone || std::time::Instant::now() >= deadline {
                break;
            }
            tokio::time::sleep(std::time::Duration::from_secs(2)).await;
        }
        let out = ign(
            &config,
            &env,
            &["tags", "provider", "create", &provider, "--compact"],
        );
        expect_ok("provider create p5alarm", &out);
        let out = ign_stdin(
            &config,
            &env,
            &["tags", "config", "create", &tag, "--file", "-", "--compact"],
            r#"{"tagType": "AtomicTag", "dataType": "Int4", "value": 0, "alarms": [{"name": "HighLimit", "enabled": true, "mode": "AboveValue", "setpointA": 100, "priority": "High"}]}"#,
        );
        expect_ok("config create the alarmed tag", &out);
        // 60s per cycle: the FIRST provider creation on a fresh
        // 8.3.3 gateway initializes the tag-provider subsystem and
        // can hold Error_Configuration past a 20s window (measured
        // on the fresh-rig run — three 20s cycles all missed; a
        // later attempt answers in seconds).
        if await_tag_ready(&config, &env, &tag, std::time::Duration::from_secs(60)).await {
            break;
        }
        eprintln!("setup: tag model stuck Error_Configuration, tearing down and retrying…");
    }
    // (The readiness guarantee the rest of the gate relies on — the
    // loop above either achieved it or the gate panics here.)
    assert!(
        await_tag_ready(&config, &env, &tag, std::time::Duration::from_secs(1)).await,
        "the alarmed tag never reached a Good model after 3 setup cycles"
    );

    // Write with LAND-VERIFICATION (same live-truth class): the write
    // answering ok is not proof the value landed while the provider's
    // model mounts — verify by read-back and retry (bounded). Before
    // the FIRST write, wait for READS to answer Good: a recreate can
    // race the old model's teardown tail (list-absence is not model-
    // freed), leaving Error_Configuration reads that clear once the
    // fresh model binds.
    async fn await_tag_ready(
        config: &Path,
        env: &LiveEnv,
        tag: &str,
        budget: std::time::Duration,
    ) -> bool {
        let deadline = std::time::Instant::now() + budget;
        loop {
            let out = ign(config, env, &["tags", "read", tag, "--compact"]);
            expect_ok("read (model-ready poll)", &out);
            let envelope = data_envelope(&out);
            let quality = envelope["data"]["results"][0]["quality"]
                .as_str()
                .unwrap_or_default();
            if quality == "Good" {
                return true;
            }
            if std::time::Instant::now() >= deadline {
                return false;
            }
            tokio::time::sleep(std::time::Duration::from_secs(2)).await;
        }
    }
    async fn write_verified(config: &Path, env: &LiveEnv, tag: &str, value: &str, what: &str) {
        let deadline = std::time::Instant::now() + std::time::Duration::from_secs(30);
        loop {
            let out = ign(
                config,
                env,
                &["tags", "write", tag, "--value", value, "--compact"],
            );
            expect_ok(what, &out);
            let out = ign(config, env, &["tags", "read", tag, "--compact"]);
            expect_ok("read-back after write", &out);
            let envelope = data_envelope(&out);
            let landed = envelope["data"]["results"][0]["value"].as_i64();
            if landed == value.parse::<i64>().ok() {
                return;
            }
            assert!(
                std::time::Instant::now() < deadline,
                "{what}: the write never landed (read-back kept disagreeing)"
            );
            tokio::time::sleep(std::time::Duration::from_secs(2)).await;
        }
    }

    // (The model-ready gate passed inside the setup loop; writes
    // below assume it.)

    // Trigger: write past the setpoint (land-verified).
    write_verified(&config, &env, &tag, "150", "write past the setpoint").await;

    // Poll `alarms active` until the event appears (bounded).
    let find_event = |envelope: &Value| -> Option<Value> {
        envelope["data"]["alarms"].as_array().and_then(|alarms| {
            alarms
                .iter()
                .find(|alarm| {
                    alarm["source"]
                        .as_str()
                        .is_some_and(|source| source.contains(&provider))
                })
                .cloned()
        })
    };
    let mut event = None;
    // POLL + RE-TRIGGER (11-06 live-truth, Rig B 8.3.3): after
    // creating the provider, the alarm engine can take a
    // LONG bounded window to register the new tag's alarm config —
    // observed: 45s+ of silent ok-polls (the config verifiably landed
    // in the model), with events flowing normally on the next attempt
    // ~50s later; warm rigs answer in 2–4s. The RE-TRIGGER (write
    // below the setpoint, then past it again — both land-verified)
    // keeps a real transition available for whichever poll window the
    // registered engine finally sees. 10 attempts ≈ 100s worst case;
    // warm runs never leave attempt 1.
    for attempt in 0..10 {
        if attempt > 0 {
            write_verified(
                &config,
                &env,
                &tag,
                "0",
                "write below the setpoint (re-trigger clear)",
            )
            .await;
            write_verified(
                &config,
                &env,
                &tag,
                "150",
                "write past the setpoint (re-trigger set)",
            )
            .await;
        }
        for _ in 0..8 {
            let out = ign(&config, &env, &["tags", "alarms", "active", "--compact"]);
            expect_ok("alarms active poll", &out);
            let envelope = data_envelope(&out);
            if let Some(found) = find_event(&envelope) {
                event = Some(found);
                break;
            }
            tokio::time::sleep(std::time::Duration::from_secs(1)).await;
        }
        if event.is_some() {
            break;
        }
    }
    let event = event.expect("the alarm event appeared (bounded retries)");

    let event_id = event["event_id"]
        .as_str()
        .expect("event_id present")
        .to_string();
    assert!(
        event["state"]
            .as_str()
            .unwrap_or_default()
            .contains("Unacknowledged"),
        "the fresh event is Active, Unacknowledged: {event}"
    );
    assert_eq!(event["priority"], "High", "{event}");
    println!(
        "alarm active: {event_id} {}",
        event["state"].as_str().unwrap_or_default()
    );

    // Acknowledge: the 3-arg form (note + username explicit).
    let out = ign(
        &config,
        &env,
        &[
            "tags",
            "alarms",
            "ack",
            &event_id,
            "--note",
            "e2e lifecycle ack",
            "--username",
            "ign-e2e",
            "--compact",
        ],
    );
    expect_ok("alarms ack (3-arg form)", &out);
    let envelope = data_envelope(&out);
    assert_eq!(envelope["data"]["acknowledged"], 1, "{envelope}");
    assert_eq!(
        envelope["data"]["unacknowledged"].as_array().map(Vec::len),
        Some(0),
        "empty remainder: {envelope}"
    );

    // The state flip: poll active until 'Active, Acknowledged'.
    let mut acknowledged = false;
    for _ in 0..20 {
        let out = ign(&config, &env, &["tags", "alarms", "active", "--compact"]);
        expect_ok("alarms active poll (ack)", &out);
        let envelope = data_envelope(&out);
        if let Some(event) = find_event(&envelope)
            && event["state"]
                .as_str()
                .is_some_and(|state| state.contains("Acknowledged"))
        {
            assert!(
                event["state"]
                    .as_str()
                    .unwrap_or_default()
                    .contains("Active"),
                "the acked alarm stays active until cleared: {event}"
            );
            acknowledged = true;
            break;
        }
        tokio::time::sleep(std::time::Duration::from_millis(500)).await;
    }
    assert!(acknowledged, "the event flipped to 'Active, Acknowledged'");
    println!("alarm acked: state flipped to Active, Acknowledged");

    // The history leg: a DEFAULT rig asserts the honest refusal LIVE
    // (exit 6 + alarm_journal_missing — the pinned default-rig
    // path); a journal-provisioned rig asserts rows instead.
    let out = ign(
        &config,
        &env,
        &[
            "tags",
            "alarms",
            "history",
            "--start",
            &(now_ms() - 600_000).to_string(),
            "--end",
            &now_ms().to_string(),
            "--compact",
        ],
    );
    if out.status.code() == Some(6) {
        let envelope = err_envelope(&out);
        assert_eq!(
            envelope["error"]["code"], "alarm_journal_missing",
            "the default-rig refusal is the journal slug: {envelope}"
        );
        println!(
            "alarm history: default-rig honest refusal pinned live \
             (alarm_journal_missing, exit 6 — the actionable journal-chain hint)"
        );
    } else {
        expect_ok("alarms history (journal-provisioned rig)", &out);
        let envelope = data_envelope(&out);
        println!(
            "alarm history: journal answered ({} row(s)) — the provisioned path",
            envelope["data"]["count"]
        );
    }

    // The journal stretch: SKIP-WITH-REASON (the documented
    // sidecar-postgres chain lives in the README; the wiremock pins
    // carry the capability proof).
    println!(
        "journal provisioning stretch: skipped — the chain (sidecar postgres container → \
         database-connection resource → alarm-journal profile → general-alarm-settings \
         singleton) is documented in the README 'Alarm history' section; provision it \
         manually and re-run to walk the provisioned path above"
    );

    // Cleanup (self-cleaning): quiet the tag value, delete the tag,
    // delete the provider.
    let _ = ign(
        &config,
        &env,
        &["tags", "write", &tag, "--value", "0", "--compact"],
    );
    let out = ign(
        &config,
        &env,
        &["tags", "config", "delete", &tag, "--yes", "--compact"],
    );
    expect_ok("config delete the alarmed tag", &out);
    let out = ign(
        &config,
        &env,
        &[
            "tags",
            "provider",
            "delete",
            &provider,
            "--yes",
            "--compact",
        ],
    );
    expect_ok("provider delete (guarded)", &out);
}

